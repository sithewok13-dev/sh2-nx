#!/bin/sh
# Assembles tools/caves/*.asm (nasm, 32-bit, each at its own org) into caves.py: the bytes of each and its labels'
# addresses, for tools/patch_exe.py. Run it after changing a cave; caves.py is committed, so building the game
# needs no assembler.
set -e
cd "$(dirname "$0")"
out=caves.py
echo "# Generated by tools/caves/build.sh from tools/caves/*.asm: do not edit." > $out
echo "CAVES = {" >> $out
for f in *.asm; do
    name=${f%.asm}
    tmp=$(mktemp -d)
    { echo "[map symbols $tmp/map]"; cat "$f"; } > "$tmp/src.asm"
    nasm -f bin "$tmp/src.asm" -o "$tmp/bin"
    org=$(awk '/^org /{print $2; exit}' "$f")
    python3 - "$name" "$org" "$tmp/bin" "$tmp/map" >> $out <<'PY'
import sys, re
name, org, binf, mapf = sys.argv[1:]
data = open(binf, 'rb').read()
syms = {}
for line in open(mapf):
    m = re.match(r'\s*([0-9A-Fa-f]+)\s+([0-9A-Fa-f]+)\s+(\S+)\s*$', line)
    if m and not m.group(3).startswith('..'):
        syms[m.group(3)] = int(m.group(2), 16)
print(f"    {name!r}: ({org}, bytes.fromhex({data.hex()!r}),")
print("        {" + ", ".join(f"{k!r}: {v:#x}" for k, v in sorted(syms.items(), key=lambda kv: kv[1])) + "}),")
PY
    rm -rf "$tmp"
done
echo "}" >> $out
